"""Build the complete Java 26.1 puzzle registry from extracted game data.
Input: directory containing mc-{blocks,items,entities,foods,recipes,es}.json.
Sources and scope are embedded in the result; no network requests during play.
"""
import json, pathlib, sys
root=pathlib.Path(__file__).resolve().parents[1]; data=pathlib.Path(sys.argv[1])
def read(name): return json.loads((data/('mc-'+name+'.json')).read_text())
blocks,items,entities,foods,recipes,es=map(read,['blocks','items','entities','foods','recipes','es'])
refs={e['id'].replace('-','_'):e for e in json.loads((root/'web/entries.json').read_text())}
blocknames={b['name'] for b in blocks};foodmap={f['name']:f['foodPoints'] for f in foods}
def base(e,kind):
 name=e['name'];ref=refs.get(name,{});translation=es.get(('entity' if kind=='mobs' else 'block' if kind=='blocks' else 'item')+'.minecraft.'+name) or es.get('block.minecraft.'+name) or e['displayName']
 return {'id':name,'title':{'en':e['displayName'],'es':translation},'reference':ref.get('id'),'image':ref.get('image'),'props':{}}
out={'version':'Java Edition 26.1','source':'https://github.com/PrismarineJS/minecraft-data/tree/master/data/pc/26.1','namesSource':'Mojang Studios · Java 26.1 Spanish language assets','license':'minecraft-data: MIT; game names and artwork: Mojang Studios','mobs':[],'blocks':[],'items':[]}
for e in entities:
 if 'mob_flags' not in e.get('metadataKeys',[]): continue
 r=base(e,'mobs');r['props']={'group':e['type'],'height':e['height'],'width':e['width'],'baby':'baby' in e.get('metadataKeys',[])};out['mobs'].append(r)
for e in blocks:
 r=base(e,'blocks');r['props']={'hardness':e.get('hardness'),'resistance':e.get('resistance'),'light':e.get('emitLight',0),'transparent':e.get('transparent',False),'tool':e.get('material','default').replace('mineable/','')};out['blocks'].append(r)
for e in items:
 r=base(e,'items');r['props']={'stack':e['stackSize'],'durability':e.get('maxDurability',0),'food':foodmap.get(e['name'],0),'placeable':e['name'] in blocknames,'craftable':str(e['id']) in recipes};out['items'].append(r)
(root/'web/game-catalog.js').write_text('/* Generated by scripts/build-game-catalog.py. See ArcadeCatalog.source for provenance. */\nconst ArcadeCatalog='+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n')
print({k:len(out[k]) for k in ['mobs','blocks','items']})
